// writeKWSConfig writes the KWSConfig to kws_config.yaml.
func writeKWSConfig(cfg *KWSConfig, path string) error {
	data, err := yaml.Marshal(cfg)
	if err != nil {
		return fmt.Errorf("failed to marshal config: %w", err)
	}

	header := "# KWS Configuration\n# Generated by kws_install\n# Edit values as needed, then run 'make up' to start.\n\n"

	if err := os.WriteFile(path, []byte(header+string(data)), 0644); err != nil {
		return fmt.Errorf("failed to write %s: %w", path, err)
	}

	return nil
}

